function tableOk(table, res) {
  if (!table) {
    if (res) res.status(400).json({ error: 'Table name is required' });
    return false;
  }
  const clean = table.toLowerCase();
  const norm = clean.replace(/-/g, '_');
  if (ALLOWED_TABLES.has(table) || ALLOWED_TABLES.has(clean) || ALLOWED_TABLES.has(norm)) {
    return true;
  }
  if (/^[a-z0-9_]+$/.test(norm)) {
    ALLOWED_TABLES.add(table);
    ALLOWED_TABLES.add(clean);
    ALLOWED_TABLES.add(norm);
    return true;
  }
  if (res) res.status(400).json({ error: `Unknown table: ${table}` });
  return false;
}


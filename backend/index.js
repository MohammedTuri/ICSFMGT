// Universal Parameter Cast Helper
function getParamPlaceholder(colName, index) {
  const jsonCols = [
    'permissions', 'attachments', 'recordData', 'previousData', 
    'customData', 'docTypes', 'types', 'customFields',
    'allowedBranches', 'allowedDocTypes', 'allowedDivisions'
  ];
  
  if (jsonCols.includes(colName)) {
    return `CASE WHEN $${index}::text IS NULL THEN '[]'::jsonb ELSE ($${index})::jsonb END`;
  }
  return `$${index}`;
}

function getRecordPrefix(table) {
  return {
    visa: 'VSID',
    eoid: 'EOID',
    eoid_normal: 'EOID',
    eoid_underage: 'EOID',
    residence_id: 'RSID',
    residence_id_cancellation: 'RSCID',
    etd: 'ETDID',
    eritrean_id: 'ERID',
    alien_passport: 'APID',
    workpermit: 'WPID',
  }[table] || null;
}

async function assignRecordNumber(client, table, id, requestedNumber) {
  if (requestedNumber || !id) return;
  const prefix = getRecordPrefix(table);
  if (!prefix) return;
  await client.query(
    `UPDATE public."${table}" SET "recordNumber" = $1 || '-' || LPAD($2::text, 6, '0') WHERE id = $2`,
    [prefix, id]
  );
}


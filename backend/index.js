// GET all records
app.get('/api/:table', async (req, res) => {
  const { table } = req.params;
  if (!tableOk(table, res)) return;
  const targetTable = table.replace(/-/g, '_');

  try {
    let query, params = [];

    if (targetTable === 'audit_logs') {
      const conditions = [];
      const { action, storeName, userId, startDate, endDate } = req.query;

      if (action)    { params.push(action);     conditions.push(`action = $${params.length}`); }
      if (storeName) { params.push(storeName);  conditions.push(`"storeName" = $${params.length}`); }
      if (userId)    { params.push(userId);     conditions.push(`"userId" = $${params.length}`); }
      if (startDate) { params.push(startDate);  conditions.push(`timestamp >= $${params.length}`); }
      if (endDate) {
        const end = endDate.includes('T') ? endDate : `${endDate}T23:59:59.999Z`;
        params.push(end);
        conditions.push(`timestamp <= $${params.length}`);
      }

      const where = conditions.length > 0 ? `WHERE ${conditions.join(' AND ')}` : '';
      query = `SELECT * FROM public.audit_logs ${where} ORDER BY timestamp DESC`;
    } else {
      query = `SELECT * FROM public."${targetTable}" ORDER BY id DESC`;
    }

    const result = await pool.query(query, params);
    res.json(result.rows);
  } catch (err) {
    console.error(`GET /${table} error:`, err.message);
    res.status(500).json({ error: err.message });
  }
});


// POST bulk import records
app.post('/api/:table/bulk', async (req, res) => {
  const { table } = req.params;
  if (!tableOk(table, res)) return;

  const { records } = req.body;
  if (!Array.isArray(records) || records.length === 0) {
    return res.status(400).json({ error: 'No records provided' });
  }

  const client = await pool.connect();
  try {
    await client.query('BEGIN');
    await ensureRecordColumns(client, table);

    for (const record of records) {
      const data = { ...record };
      delete data.id;
      if (!data.createdAt) data.createdAt = new Date().toISOString();
      if (!data.updatedAt) data.updatedAt = new Date().toISOString();
      if (!data.attachments) data.attachments = [];

      const cols   = Object.keys(data);
      const vals   = processValues(Object.values(data));
      const quoted = cols.map(c => `"${c}"`).join(', ');
      const ph     = cols.map((c, i) => getParamPlaceholder(c, i + 1)).join(', ');

      const inserted = await client.query(
        `INSERT INTO public."${table}" (${quoted}) VALUES (${ph}) RETURNING id, "recordNumber"`,
        vals
      );
      await assignRecordNumber(client, table, inserted.rows[0]?.id, inserted.rows[0]?.recordNumber);
    }

    await client.query('COMMIT');
    res.json({ success: true });
  } catch (err) {
    await client.query('ROLLBACK');
    console.error(`POST /${table}/bulk error:`, err.message);
    res.status(500).json({ error: err.message });
  } finally {
    client.release();
  }
});


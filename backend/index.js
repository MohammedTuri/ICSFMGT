// PUT update a record by ID
app.put('/api/:table/:id', async (req, res) => {
  const { table, id } = req.params;
  if (!tableOk(table, res)) return;
  const targetTable = table.replace(/-/g, '_');

  let data = { ...req.body };
  delete data.id;

  if (Object.keys(data).length === 0) {
    return res.status(400).json({ error: 'No data provided' });
  }

  try {
    // Skip updatedAt if it's not present in the request body
    // (The database may not have this column yet)
    if (!data.updatedAt && Object.keys(data).includes('isActive')) {
      // Only branches table uses isActive, and we want to avoid updatedAt errors
      // so don't add it if it's not already in the request
    }

    const cols = Object.keys(data);
    const vals = processValues(Object.values(data));
    const set  = cols.map((c, i) => `"${c}" = ${getParamPlaceholder(c, i + 1)}`).join(', ');

    vals.push(id);
    const result = await pool.query(
      `UPDATE public."${targetTable}" SET ${set} WHERE id = $${vals.length} RETURNING *`,
      vals
    );
    res.json(result.rows[0] || { success: true });
  } catch (err) {
    console.error(`PUT /${table}/${id} error:`, err.message);
    res.status(500).json({ error: err.message });
  }
});

